const {test,expect}=require('@playwright/test');
test('G4 public : interface, trois thèmes et moteur Python réellement exécuté',async({page})=>{
 test.setTimeout(90000);
 const browserErrors=[];
 page.on('pageerror',error=>browserErrors.push('PAGE: '+error.message));
 page.on('console',message=>{if(message.type()==='error')browserErrors.push('CONSOLE: '+message.text());});
 page.on('response',response=>{if(response.status()>=400)browserErrors.push('HTTP '+response.status()+' '+response.url());});
 const response=await page.goto('http://127.0.0.1:5180/microalbert-lab/',{waitUntil:'networkidle'});
 try {
  await expect(page.locator('#student-heading')).toBeVisible({timeout:15000});
 } catch(error) {
  const html=await page.locator('body').innerText().catch(()=>'<body inaccessible>');
  console.error('DIAGNOSTIC G4 PUBLIC — HTTP:',response?.status(),'URL:',page.url());
  console.error('DIAGNOSTIC G4 PUBLIC — HTML:',html.slice(0,3000));
  console.error('DIAGNOSTIC G4 PUBLIC — ERREURS:',browserErrors.join('\\n'));
  await page.screenshot({path:'test-results/g4-public-page-failure.png',fullPage:true}).catch(()=>{});
  throw error;
 }
 await expect(page.getByText('Illustration indisponible.')).toHaveCount(0);
 await expect(page.locator('.stage--no-illustration')).toHaveCount(0);
 const mascot=page.locator('.mascot-panel img');
 await expect(mascot).toBeVisible();
 await expect.poll(()=>mascot.evaluate(img=>img.complete && img.naturalWidth>0)).toBe(true);
 const desktopStage=await page.locator('.stage').boundingBox();
 const desktopMascot=await page.locator('.mascot-panel').boundingBox();
 expect(desktopMascot.width).toBeLessThan(desktopStage.width*0.35);
 expect(desktopStage.width).toBeGreaterThan(800);
 const heroPosition=await page.locator('.mascot-panel').evaluate(el=>getComputedStyle(el).position);
 expect(heroPosition).toBe('sticky');
 await page.evaluate(()=>window.scrollTo(0,500));
 await expect.poll(()=>page.locator('.mascot-panel').evaluate(el=>el.getBoundingClientRect().top)).toBeGreaterThanOrEqual(0);
 await page.evaluate(()=>window.scrollTo(0,0));
 await page.setViewportSize({width:390,height:844});
 await expect(page.locator('#student-heading')).toBeVisible();
 const mobileStage=await page.locator('.stage').boundingBox();
 const mobileMascot=await page.locator('.mascot-panel').boundingBox();
 expect(mobileMascot.width).toBeLessThanOrEqual(mobileStage.width);
 await page.setViewportSize({width:1280,height:800});
 for(const theme of ['light','dark','projector']){
  await page.getByLabel('Affichage :').selectOption(theme);
  await expect(page.locator('.app')).toHaveAttribute('data-theme',theme);
 }
 await page.getByLabel('Affichage :').selectOption('light');
 await expect(page.getByRole('heading', {name: 'Entraîne-toi en Python'})).toBeVisible();
 await page.getByRole('button', {name: '5', exact: true}).click();
 await page.getByRole('button', {name: 'Écrire mon programme'}).click();
 const editor=page.getByRole('textbox',{name:/Code Python, édition au clavier/});
 await expect(editor).toBeVisible();
 await editor.fill('def total_seuil(mesures, seuil):\n    return 2 + 3');
 await page.getByRole('button',{name:'Lancer le test'}).click();
 await expect(page.getByRole('status').filter({hasText:'Exécution terminée'})).toBeVisible({timeout:40000});
 await expect(page.getByLabel('Résultats de l’exécution')).toHaveText('5');
 await expect(page.getByRole('heading', {name:'Résultat attendu pour ce test'})).toBeVisible();
 await editor.fill('print(1 / 0)');
 await page.getByRole('button',{name:'Lancer le test'}).click();
 await expect(page.getByRole('status').filter({hasText:'Exécution en erreur'})).toBeVisible({timeout:40000});
 await editor.fill('while True:\n    pass');
 await page.getByRole('button',{name:'Lancer le test'}).click();
 await page.getByRole('button',{name:'Arrêter l’exécution'}).click();
 await expect(page.getByRole('status').filter({hasText:'Exécution arrêtée'})).toBeVisible();
});

test('Pages : l’élève prévoit, programme et teste sur les deux niveaux, hors ligne', async ({ page }) => {
 const requests = [];
 await page.route('**/*', route => {
  const url = new URL(route.request().url());
  if (url.origin === 'http://127.0.0.1:5180' && !url.pathname.startsWith('/api/')) return route.continue();
  requests.push(url.href);
  return route.abort();
 });
 await page.setViewportSize({width:390,height:844});
 await page.goto('./');
 const level = page.getByLabel('Ton niveau');
 const editor = page.getByRole('textbox', {name:/Code Python, édition au clavier/});
 const next = page.getByRole('button', {name:'Écrire mon programme'});
 const testCase = page.getByRole('region', {name:'Exemple de test justifié'});
 await expect(level).toHaveValue('0');
 await expect(page.getByRole('heading', {name:'1. Prévois le résultat'})).toBeVisible();
 await expect(editor).toHaveCount(0);
 const firstChoices = await page.getByRole('group', {name:'Résultat attendu'}).boundingBox();
 expect(firstChoices.y + firstChoices.height).toBeLessThanOrEqual(844);
 await expect(next).toHaveCount(0);
 await expect(page.getByLabel('Ma question au tuteur')).toHaveCount(0);
 await page.getByRole('button', {name:'0', exact:true}).click();
 await expect(page.getByText(/La mesure égale au seuil compte-t-elle/)).toBeVisible();
 await expect(next).toHaveCount(0);
 await page.getByRole('button', {name:'5', exact:true}).click();
 await expect(page.getByText(/La mesure 5 atteint le seuil/)).toBeVisible();
 await next.click();
 await expect(page.getByRole('heading', {name:'2. Programme et teste'})).toBeFocused();
 await expect(editor).toHaveValue(/def total_seuil/);
 await page.getByText('J’ai besoin d’un indice', {exact:true}).filter({visible:true}).click();
 await expect(page.getByText(/quelle comparaison te permet/)).toBeVisible();
 const firstDraft = 'def total_seuil(mesures, seuil):\n    return 0\n';
 await editor.fill(firstDraft);
 await page.getByRole('button', {name:'Lancer le test'}).click();
 await expect(page.getByLabel('Résultats de l’exécution')).toHaveText('0');
 await expect(page.getByRole('heading', {name:'Écart pour ce test'})).toBeVisible();
 await page.getByText('Voir un exemple de test justifié', {exact:true}).filter({visible:true}).click();
 await expect(testCase).toContainText('total_seuil([5, 4], 5)');
 await expect(testCase).toContainText('G1SNSIN03316');
 await level.selectOption({label:'Terminale'});
 await expect(page.getByRole('heading', {name:'Explorer les salles accessibles'})).toBeVisible();
 await expect(editor).toHaveCount(0);
 await page.getByRole('button', {name:"['A', 'B', 'A']", exact:true}).click();
 await expect(page.getByText(/une salle déjà visitée/)).toBeVisible();
 await page.getByRole('button', {name:"['A', 'B']", exact:true}).click();
 await next.click();
 await expect(editor).toHaveValue(/def salles_accessibles/);
 await editor.fill('def salles_accessibles(graphe, depart):\n    return [depart]\n');
 await page.getByRole('button', {name:'Lancer le test'}).click();
 await expect(page.getByLabel('Résultats de l’exécution')).toHaveText("['A']");
 await page.getByText('Voir un exemple de test justifié', {exact:true}).filter({visible:true}).click();
 await expect(testCase).toContainText('26-NSIJ1ME1');
 await expect(testCase).toContainText("['A', 'B']");
 await level.selectOption({label:'Première'});
 await expect(editor).toHaveValue(firstDraft);
 await expect(page.getByLabel('Jeton du pilote enseignant')).toHaveCount(0);
 expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
 expect(requests).toEqual([]);
});
